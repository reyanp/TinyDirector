"""Real-Blender checks for OVERRIDE explainer scenes (blender_engine/explainer.py).

  blender -b --factory-startup --python blender_engine/explainer_check.py [-- --render DIR] [--save FILE]

Builds sample specs in every layout and checks the read-back: labels exact, every element in frame, no two
elements overlapping, motion keyed, links drawn; the camera can focus each element (ring on, others off); the
caption works; unknown shapes are refused before anything is built; a circuit build removes the scene.
"""

import sys
from pathlib import Path

import bpy

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from blender_engine import circuit, direction, explainer  # noqa: E402

FAILS = []
ARGS = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []


def ok(cond, msg):
    print(("  PASS " if cond else "  FAIL ") + msg, flush=True)
    if not cond:
        FAILS.append(msg)


def spec(layout, n=4, shapes=None, long_labels=False):
    shapes = shapes or ["cloud", "drop", "sphere", "tree", "rock", "cabin", "gear"]
    labels = ["Evaporation from the ocean surface", "Condensation", "Precipitation", "Collection", "Runoff",
              "Groundwater", "Transpiration"] if long_labels else ["Ocean", "Cloud", "Rain", "Rivers", "Sun",
                                                                  "Plants", "Ice"]
    els = [{"id": f"e{i}", "label": labels[i][:32], "shape": shapes[i % len(shapes)],
            "color": ["#3E8EDE", "#DDE6F0", "#5FB0FF", "#3BAA7A", "#FFC940", "#6CCB5F", "#BFE8FF"][i],
            "size": ["large", "medium", "small", "medium", "large", "small", "medium"][i],
            "motion": ["none", "bob", "pulse", "spin", "none", "bob", "none"][i], "glow": i == 4}
           for i in range(n)]
    links = [{"from": f"e{i}", "to": f"e{(i + 1) % n}", "label": ["evaporates", "falls", "flows", "returns",
                                                                  "warms", "grows", "melts"][i]}
             for i in range(n if layout == "cycle" else n - 1)]
    return {"title": f"Sample {layout} lesson", "layout": layout, "elements": els, "links": links}


# designs Nemotron wrote in a live run (director/dev/explainer_e2e.py): a cycle with a chord through the middle
RECORDED = [{"title": "How does the water cycle work?", "layout": "cycle", "elements": [
    {"id": "ocean", "label": "Ocean", "shape": "sphere", "color": "#1E90FF", "size": "large", "motion": "bob",
     "glow": True},
    {"id": "clouds", "label": "Clouds", "shape": "cloud", "color": "#B0C4DE", "size": "medium", "motion": "none"},
    {"id": "rain", "label": "Rain", "shape": "drop", "color": "#4682B4", "size": "small", "motion": "none"},
    {"id": "ground", "label": "Ground", "shape": "rock", "color": "#8B4513", "size": "medium", "motion": "none"},
    {"id": "sun", "label": "Sun", "shape": "sphere", "color": "#FFD700", "size": "large", "motion": "spin",
     "glow": True}],
    "links": [{"from": "sun", "to": "ocean", "label": "heats"}, {"from": "ocean", "to": "clouds", "label": "evaporates"},
              {"from": "clouds", "to": "rain", "label": "forms"}, {"from": "rain", "to": "ground", "label": "falls"},
              {"from": "ground", "to": "ocean", "label": "flows back"}]}]


def req(s, action="build"):
    return {"kind": "explainer", "schema_version": 1, "request_id": f"chk_{s['layout'] if s else 'x'}",
            "action": action, "spec": s, "banner": "Generated lesson (OVERRIDE) · not verified",
            "legend": "Generated by Nemotron from your question: content is not checked by a calculator or source."}


def main():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    out_dir = Path(ARGS[ARGS.index("--render") + 1]) if "--render" in ARGS else None
    cases = [("cycle", 4, False), ("row", 3, False), ("flow", 5, True), ("hub", 6, False), ("stack", 4, False),
             ("grid", 7, True)]
    for layout, n, long_labels in cases + [("recorded", i, False) for i in range(len(RECORDED))]:
        print(f"== {layout} ({n if layout != 'recorded' else RECORDED[n]['title']}"
              f"{', long labels' if long_labels else ''})")
        s = spec(layout, n, long_labels=long_labels) if layout != "recorded" else RECORDED[n]
        res = explainer.make_result(f"chk_{layout}", req(s))
        ok(res["status"] == "ok" and res["applied"] == 1, f"built ({res['errors']})")
        rb = res["explainer"]
        ok(rb["present"] and rb["title"] == s["title"], "present, title shown")
        labels = {k: v["label"] for k, v in rb["elements"].items()}
        ok(labels == {e["id"]: e["label"] for e in s["elements"]}, "every label exact")
        out = [k for k, v in rb["elements"].items() if not v["in_frame"]]
        ok(not out, f"every element in frame {out}")
        ok(not rb["overlaps"], f"no overlapping elements {rb['overlaps']}")
        moving = {k for k, v in rb["elements"].items() if v["animated"]}
        ok(moving == {e["id"] for e in s["elements"] if e.get("motion", "none") != "none"},
           f"motion keyed on {sorted(moving)}")
        ok(all(ln["drawn"] for ln in rb["links"]) and len(rb["links"]) == len(s["links"]), "links drawn")
        ok("not verified" in (rb["banner"] or "") and "not checked" in (rb["legend"] or ""), "labeled not verified")
        if out_dir:
            out_dir.mkdir(parents=True, exist_ok=True)
            circuit.render_preview(out_dir / f"{layout}{n if layout == 'recorded' else ''}.jpg", 960, 540,
                                   samples=16, file_format="JPEG")
        if layout == "cycle":
            for e in s["elements"]:
                errs = direction.apply({"kind": "direct", "schema_version": 1, "request_id": "f", "focus": e["id"],
                                        "transition_s": 0})
                rings = {o.get("explainer_group") for o in bpy.data.objects
                         if o.get("explainer_ring") and not o.hide_render}
                ok(not errs and rings == {e["id"]}, f"focus {e['id']}: ring on it only {errs}")
                if out_dir and e["id"] == "e1":
                    circuit.render_preview(out_dir / "cycle_focus_e1.jpg", 960, 540, samples=16, file_format="JPEG")
            errs = direction.apply({"kind": "direct", "schema_version": 1, "request_id": "o", "focus": "overview",
                                    "caption": "Water keeps moving around the cycle.", "transition_s": 0})
            rb2 = direction.read_back()
            ok(not errs and rb2["caption"] == "Water keeps moving around the cycle.", "caption on the HUD")
            ok(not any(o.get("explainer_ring") and not o.hide_render for o in bpy.data.objects), "overview: no ring")
            ok(explainer.read_back()["elements"] == rb["elements"], "camera moves change nothing in the lesson")
    print("== refused")
    bad = spec("row", 3)
    bad["elements"][0]["shape"] = "bpy.ops.wm.quit_blender"
    res = explainer.make_result("bad", req(bad))
    ok(res["status"] == "error" and "unknown shape" in " ".join(res["errors"]), f"unknown shape refused {res['errors']}")
    ok(explainer.present(), "the previous lesson is still on stage after a refused request")
    print("== a circuit build removes it")
    circuit.make_result("circ", {"kind": "circuit", "schema_version": 1, "request_id": "circ", "action": "build",
                                 "circuit": {"source_v": 9.0, "resistance_ohm": 330.0, "led_vf": 2.0},
                                 "display": circuit.default_display() if hasattr(circuit, "default_display") else None}) \
        if hasattr(circuit, "default_display") else circuit.clear()
    ok(not explainer.present() and not any(o.get("explainer_part") for o in bpy.data.objects),
       "no explainer object left")
    if "--save" in ARGS:
        explainer.make_result("save", req(spec("cycle", 4)))
        bpy.ops.wm.save_as_mainfile(filepath=ARGS[ARGS.index("--save") + 1])
    print("explainer_check: " + ("ALL PASSED" if not FAILS else f"{len(FAILS)} FAILED: {FAILS}"))
    sys.exit(1 if FAILS else 0)


main()
