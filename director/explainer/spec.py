"""The OVERRIDE explainer spec: schema validation + lint (pure data, never code).

The schema is `$defs/spec` of shared/schema/explainer_request_v1.json (additive). The lint adds what a schema
cannot say: element ids unique, links between existing elements, every narration step focuses on an element or
the overview, narration short enough to speak, no links / phone numbers / markdown in anything shown or spoken.
"""

from __future__ import annotations

import json
import re
from functools import lru_cache

from jsonschema import Draft202012Validator

from .. import paths

BANNER = "Generated lesson (OVERRIDE) · not verified"
LEGEND = "Generated by Nemotron from your question: content is not checked by a calculator or source."
MOCK_BANNER = "MOCK lesson (OVERRIDE, offline model) · not verified"
MOCK_LEGEND = "Written by the offline MOCK model, not Nemotron: content is not checked by a calculator or source."
MAX_WORDS = 130  # spoken narration (all steps)

_URL = re.compile(r"(?i)\bhttps?://|\bwww\.|\b[a-z0-9-]+\.(com|net|org|io|gov|edu|co|info|app|xyz)\b")
_PHONE = re.compile(r"\b\d{3}[-. )]\s*\d{3}[-. ]\d{4}\b")
_MARKDOWN = re.compile(r"\*\*|`|^\s*[-*#]\s", re.M)


@lru_cache(maxsize=1)
def request_schema() -> dict:
    return json.loads((paths.SCHEMA_DIR / "explainer_request_v1.json").read_text(encoding="utf-8"))


@lru_cache(maxsize=1)
def _spec_validator() -> Draft202012Validator:
    s = request_schema()
    return Draft202012Validator({**s["$defs"]["spec"], "$defs": s["$defs"]})


@lru_cache(maxsize=1)
def _request_validator() -> Draft202012Validator:
    return Draft202012Validator(request_schema())


def shapes() -> list[str]:
    return list(request_schema()["$defs"]["spec"]["properties"]["elements"]["items"]["properties"]["shape"]["enum"])


def layouts() -> list[str]:
    return list(request_schema()["$defs"]["spec"]["properties"]["layout"]["enum"])


def _errs(validator, obj) -> list[str]:
    return [f"{'/'.join(map(str, e.absolute_path)) or '(root)'}: {e.message}"
            for e in sorted(validator.iter_errors(obj), key=lambda e: list(e.absolute_path))]


def narration_text(spec: dict) -> str:
    return " ".join(s["say"].strip() for s in spec.get("narration", []))


def validate(spec) -> list[str]:
    """Schema + lint problems (empty = the spec can be built)."""
    errs = _errs(_spec_validator(), spec)
    if errs:
        return errs
    ids = [e["id"] for e in spec["elements"]]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        errs.append(f"elements: duplicate ids {dupes}")
    labels = [e["label"].strip().lower() for e in spec["elements"]]
    if len(set(labels)) != len(labels):
        errs.append("elements: two elements have the same label")
    pairs = set()
    for i, ln in enumerate(spec["links"]):
        if ln["from"] not in ids or ln["to"] not in ids:
            errs.append(f"links/{i}: from/to must be element ids ({', '.join(ids)})")
        elif ln["from"] == ln["to"]:
            errs.append(f"links/{i}: a link must connect two different elements")
        elif (ln["from"], ln["to"]) in pairs:
            errs.append(f"links/{i}: duplicate link {ln['from']} -> {ln['to']}")
        pairs.add((ln["from"], ln["to"]))
    if spec["layout"] == "cycle" and len(ids) < 3:
        errs.append("layout cycle needs at least 3 elements")
    for i, step in enumerate(spec["narration"]):
        if step["focus"] != "overview" and step["focus"] not in ids:
            errs.append(f"narration/{i}/focus: must be an element id or \"overview\", not {step['focus']!r}")
    words = len(narration_text(spec).split())
    if words > MAX_WORDS:
        errs.append(f"narration is {words} words; keep all steps together under {MAX_WORDS} words")
    shown = [spec["title"], spec["summary"], *[e["label"] for e in spec["elements"]],
             *[ln.get("label", "") for ln in spec["links"]], *[s["say"] for s in spec["narration"]],
             *spec["key_points"]]
    for t in shown:
        if _URL.search(t):
            errs.append(f"no web addresses or domains anywhere (found in {t[:60]!r})")
        if _PHONE.search(t):
            errs.append(f"no phone numbers anywhere (found in {t[:60]!r})")
        if _MARKDOWN.search(t):
            errs.append(f"plain text only, no markdown (found in {t[:60]!r})")
    return errs


def build_request(rid: str, spec: dict, mock: bool = False) -> dict:
    return {"kind": "explainer", "schema_version": 1, "request_id": rid, "action": "build", "spec": spec,
            "banner": MOCK_BANNER if mock else BANNER, "legend": MOCK_LEGEND if mock else LEGEND}


def clear_request(rid: str) -> dict:
    return {"kind": "explainer", "schema_version": 1, "request_id": rid, "action": "clear"}


def validate_request(req: dict) -> list[str]:
    errs = _errs(_request_validator(), req)
    if not errs and req.get("action") == "build":
        errs = validate(req["spec"])
    return errs
